import assert from 'node:assert/strict';
import { classifyZone, deviceState, distanceMeters, firebaseReadError, isSosRisingEdge, locationLabel, locationState, normalizePoint, safeZoneState } from '../web/location-state.mjs';

const now = 1_800_000_000_000;
const current = { lat: 33.7, lng: 73.1, timestamp: now - 20_000 };
const stale = { lat: 33.7, lng: 73.1, timestamp: now - 180_000 };
const recent = { lat: '33.7', lng: '73.1', lastSeen: String(now - 5_000) };
const freshnessBoundary = { lat: 33.7, lng: 73.1, timestamp: now - 15_000 };

assert.equal(locationState(current, now), 'OFFLINE');
assert.equal(locationState(recent, now), 'LIVE');
assert.deepEqual(normalizePoint({ lat: '33.7', lng: '73.1', timestamp: now }), { lat: 33.7, lng: 73.1, timestamp: now });
assert.deepEqual(normalizePoint({ latt: '33.7', longg: '73.1', updatedAt: now }), { latt: '33.7', longg: '73.1', updatedAt: now, lat: 33.7, lng: 73.1, timestamp: now });
assert.deepEqual(normalizePoint({ latitude: '33.7', longitude: '73.1', recordedAt: now }), { latitude: '33.7', longitude: '73.1', recordedAt: now, lat: 33.7, lng: 73.1, timestamp: now });
assert.equal(locationState(stale, now), 'OFFLINE');
assert.equal(locationLabel(locationState(stale, now)), 'Last known location');
assert.equal(locationState(null, now), 'LOCATION UNAVAILABLE');
assert.equal(locationLabel(locationState(null, now)), 'Location unavailable');
assert.equal(deviceState(current, now), 'OFFLINE');
assert.equal(deviceState(stale, now), 'OFFLINE');
assert.equal(deviceState(recent, now), 'ONLINE');
assert.equal(deviceState(freshnessBoundary, now), 'ONLINE');
assert.equal(deviceState({ ...freshnessBoundary, timestamp: freshnessBoundary.timestamp - 1 }, now), 'OFFLINE');
assert.equal(deviceState(null, now), 'OFFLINE');
assert.equal(deviceState({ lat: 33.7, lng: 73.1 }, now), 'OFFLINE');
assert.equal(locationState(stale, now), 'OFFLINE');
assert.equal(isSosRisingEdge(0, 1), true);
assert.equal(isSosRisingEdge(1, 1), false);
assert.equal(isSosRisingEdge(1, 0), false);
assert.equal(isSosRisingEdge(undefined, 1), false);
assert.equal(isSosRisingEdge('0', '1'), true);
const zoneCenter = { lat: 33.6844, lng: 73.0479 };
const safeZone = { name: 'Home', lat: zoneCenter.lat, lng: zoneCenter.lng, radiusMeters: 150 };
assert.equal(distanceMeters(zoneCenter, zoneCenter), 0);
assert.equal(classifyZone(150, 150, undefined).inside, true,'the configured radius boundary is inside');
assert.equal(classifyZone(170, 150, true).inside, true,'hysteresis retains the inside state through its outer margin');
assert.equal(classifyZone(170.1, 150, true).inside, false);
assert.equal(classifyZone(130, 150, false).inside, true,'re-entry occurs at the inner hysteresis boundary');
assert.equal(safeZoneState({ ...zoneCenter, timestamp: now }, safeZone, undefined, now).state, 'INSIDE');
assert.equal(safeZoneState({ lat: 33.6845, lng: 73.0479, timestamp: now }, safeZone, undefined, now).state, 'INSIDE');
assert.equal(safeZoneState({ lat: 33.69, lng: 73.0479, timestamp: now }, safeZone, true, now).state, 'OUTSIDE');
assert.equal(safeZoneState({ lat: 33.6845, lng: 73.0479, timestamp: now }, safeZone, true, now).state, 'INSIDE');
assert.equal(safeZoneState({ lat: 33.6845, lng: 73.0479, timestamp: now }, safeZone, false, now).state, 'INSIDE');
assert.equal(safeZoneState({ lat: 33.6844 + 149 / 111_000, lng: 73.0479, timestamp: now }, safeZone, undefined, now).state, 'INSIDE');
assert.equal(safeZoneState({ lat: 33.6844 + 151 / 111_000, lng: 73.0479, timestamp: now }, safeZone, undefined, now).state, 'OUTSIDE');
assert.equal(safeZoneState({ lat: 33.6844 + 165 / 111_000, lng: 73.0479, timestamp: now }, safeZone, true, now).state, 'INSIDE');
assert.equal(safeZoneState({ lat: 33.6844 + 135 / 111_000, lng: 73.0479, timestamp: now }, safeZone, false, now).state, 'OUTSIDE');
assert.equal(safeZoneState({ lat: 33.69, lng: 73.0479, timestamp: now }, safeZone, true, now).transition, 'geofence_exit');
assert.equal(safeZoneState({ lat: 33.69, lng: 73.0479, timestamp: now }, safeZone, false, now).transition, null);
assert.equal(safeZoneState({ lat: 33.6845, lng: 73.0479, timestamp: now }, safeZone, false, now).transition, 'geofence_enter');
assert.equal(safeZoneState({ lat: 33.69, lng: 73.0479, timestamp: now }, safeZone, true, now).transition, 'geofence_exit');
assert.equal(safeZoneState(null, safeZone, undefined, now).state, 'UNKNOWN');
assert.equal(safeZoneState({ lat: 33.6844, lng: 73.0479 }, safeZone, undefined, now).state, 'UNKNOWN');
assert.equal(safeZoneState({ lat: 91, lng: 73, timestamp: now }, safeZone, undefined, now).state, 'UNKNOWN');
assert.equal(safeZoneState({ lat: 33.7, lng: 73.1, timestamp: now - 15_001 }, safeZone, true, now).state, 'UNKNOWN');
assert.equal(safeZoneState({ lat: 33.6844, lng: 73.0479, timestamp: now, clientEstimatedTimestamp: true }, safeZone, undefined, now).state, 'UNKNOWN');
assert.equal(safeZoneState({ lat: 33.6844, lng: 73.0479, timestamp: now, clientEstimatedTimestamp: true, clientObservedFresh: true }, safeZone, undefined, now).state, 'INSIDE');
assert.equal(safeZoneState({ lat: 33.69, lng: 73.0479, timestamp: now }, { latitude: zoneCenter.lat, longitude: zoneCenter.lng, radius: 150 }, true, now).transition, 'geofence_exit');
assert.ok(distanceMeters(zoneCenter, { lat: 33.6845, lng: 73.0479 }) < 20);
const outsideZone = distanceMeters(zoneCenter, { lat: 33.69, lng: 73.0479 });
assert.equal(classifyZone(outsideZone, 150, undefined).transition, null);
assert.equal(classifyZone(outsideZone, 150, true).transition, 'geofence_exit');
assert.equal(classifyZone(outsideZone, 150, false).transition, null);
assert.equal(classifyZone(distanceMeters(zoneCenter, { lat: 33.6845, lng: 73.0479 }), 150, false).transition, 'geofence_enter');
assert.equal(normalizePoint({ lat: 91, lng: 73, timestamp: now }), null);
assert.equal(normalizePoint({ lat: 33, lng: -181, timestamp: now }), null);
assert.equal(normalizePoint({ lat: 0, lng: 0, timestamp: now }), null);
assert.equal(normalizePoint({ lat: 'bad', lng: 73, timestamp: now }), null);

// A failed Firebase read must keep the cached point available as last known,
// and report the connection/rule problem separately from device status.
const cached = normalizePoint(stale);
assert.equal(locationState(cached, now), 'OFFLINE');
assert.match(firebaseReadError({ code: 'NETWORK_ERROR' }), /unreachable/i);
assert.match(firebaseReadError({ code: 'PERMISSION_DENIED' }), /denied/i);

console.log('Location state checks passed: GPS freshness, safe-zone distance/hysteresis/transitions, stale or invalid UNKNOWN states, legacy zone fields, and Firebase read failures.');
